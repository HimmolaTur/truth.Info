async function resolveImageForUrl(pageUrl, coverFallback) {
  const fallback =
    typeof coverFallback === "string" && coverFallback.trim()
      ? coverFallback.trim()
      : DEFAULT_FALLBACK_IMG;
  let imagePath = fallback;
  try {
    console.log("Page fetch:", pageUrl);
    const html = await fetchHtml(pageUrl);
    const og = extractOg(html);
    if (og.image) {
      const local = await downloadImage(og.image, pageUrl);
      if (local) imagePath = local;
    }
  } catch (e) {
    console.warn("Fetch/meta skip:", pageUrl, e.message);
  }
  return imagePath;
}

function createDbClient(connectionString) {
  const c = new Client({ connectionString, ssl: { rejectUnauthorized: false } });
  c.on("error", (err) => {
    if (!c._ending) console.warn("pg client error:", err.message);
  });
  return c;
}

async function queryOnce(connectionString, text, params) {
  const c = createDbClient(connectionString);
  await c.connect();
  try {
    await c.query("SET statement_timeout = '60s'");
    return await c.query(text, params);
  } finally {
    await c.end();
  }
}

