/** Сайты вроде meduza.io без таймаута могут «висеть» на TLS/ожидании ответа. */
const FETCH_TIMEOUT_MS = 30000;

async function fetchWithTimeout(url, options = {}) {
  const controller = new AbortController();
  const id = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  try {
    return await fetch(url, { ...options, signal: controller.signal });
  } finally {
    clearTimeout(id);
  }
}

function loadEnvLocal() {
  const envPath = path.join(__dirname, "..", ".env.local");
  if (!fs.existsSync(envPath)) {
    console.error("No .env.local");
    process.exit(1);
  }
  for (const line of fs.readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq === -1) continue;
    const key = t.slice(0, eq).trim();
    let val = t.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    if (!process.env[key]) process.env[key] = val;
  }
}

function decodeEntities(s) {
  if (!s) return s;
  return s
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(parseInt(n, 10)));
}

function metaContent(html, attrName, attrValue) {
  const pats = [
    new RegExp(
      `<meta[^>]+${attrName}=["']${attrValue.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}["'][^>]+content=["']([^"']+)["']`,
      "i"
    ),
    new RegExp(
      `<meta[^>]+content=["']([^"']+)["'][^>]+${attrName}=["']${attrValue.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}["']`,
      "i"
    ),
  ];
  for (const re of pats) {
    const m = html.match(re);
    if (m) return decodeEntities(m[1]);
  }
  return null;
}

function extractOg(html) {
  return {
    title: metaContent(html, "property", "og:title") || metaContent(html, "name", "twitter:title"),
    image: metaContent(html, "property", "og:image") || metaContent(html, "name", "twitter:image"),
    description: metaContent(html, "property", "og:description"),
  };
}

async function fetchHtml(url) {
  const res = await fetchWithTimeout(url, {
    redirect: "follow",
    headers: { "User-Agent": UA, Accept: "text/html,application/xhtml+xml" },
  });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

async function responseToBuffer(res) {
  if (typeof res.buffer === "function") return res.buffer();
  return Buffer.from(await res.arrayBuffer());
}

async function downloadImage(imageUrl, pageUrl) {
  if (!imageUrl || !imageUrl.startsWith("http")) return null;
  let abs = imageUrl;
  try {
    abs = new URL(imageUrl, pageUrl).href;
  } catch {
    return null;
  }
  const imagesDir = path.join(__dirname, "..", "public", "images");
  fs.mkdirSync(imagesDir, { recursive: true });
  const res = await fetchWithTimeout(abs, {
    headers: {
      "User-Agent": UA,
      Referer: pageUrl,
      Accept: "image/avif,image/webp,image/*,*/*;q=0.8",
    },
  });
  if (!res.ok) {
    console.warn("Image HTTP", res.status, abs);
    return null;
  }
  const ct = (res.headers.get("content-type") || "").split(";")[0].trim().toLowerCase();
  let ext = ".jpg";
  if (ct.includes("png")) ext = ".png";
  else if (ct.includes("webp")) ext = ".webp";
  else if (ct.includes("gif")) ext = ".gif";
  const hash = crypto.createHash("sha1").update(abs).digest("hex").slice(0, 12);
  const name = `ingest-${hash}${ext}`;
  const full = path.join(imagesDir, name);
  const buf = await responseToBuffer(res);
  if (buf.length < 500) {
    console.warn("Image too small, skip:", abs);
    return null;
  }
  fs.writeFileSync(full, buf);
  return `/images/${name}`;
}

