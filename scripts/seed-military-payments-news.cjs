async function main() {
  loadEnvLocal();
  const url = process.env.DATABASE_URL;
  if (!url) {
    console.error("DATABASE_URL is missing in .env.local");
    process.exit(1);
  }

  const client = new Client({
    connectionString: url,
    ssl: { rejectUnauthorized: false },
  });
  await client.connect();

  try {
    await client.query("BEGIN");
    // DELETE вместо TRUNCATE: у части pooler (Supabase) TRUNCATE в транзакции рвёт соединение.
    await client.query("DELETE FROM news");
    console.log("Cleared news.");

    let i = 0;
    const now = Date.now();
    for (const a of ARTICLES) {
      const image_url = IMAGES[i % IMAGES.length];
      i += 1;
      const createdAt = new Date(now - a.daysAgo * 86400000);
      await client.query(
        `INSERT INTO news (title, content, image_url, category, tags, is_important, is_featured, created_at, updated_at)
         VALUES ($1, $2, $3, $4, $5::text[], $6, $7, $8, NOW())`,
        [
          a.title,
          a.content,
          image_url,
          a.category,
          a.tags,
          a.is_important,
          a.is_featured,
          createdAt,
        ]
      );
    }
    await client.query("COMMIT");
    console.log(`Inserted ${ARTICLES.length} articles.`);
  } catch (e) {
    await client.query("ROLLBACK").catch(() => {});
    throw e;
  } finally {
    await client.end();
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
